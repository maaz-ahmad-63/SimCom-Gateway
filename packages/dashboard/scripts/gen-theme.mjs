// Generates the dashboard's theme tokens (CSS variables) from the Tailwind palettes the app uses.
// Dark = Tailwind's own values (the current look). Light = a tuned counterpart per shade.
import fs from 'node:fs';

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const P = {
  slate: ['#f8fafc', '#f1f5f9', '#e2e8f0', '#cbd5e1', '#94a3b8', '#64748b', '#475569', '#334155', '#1e293b', '#0f172a', '#020617'],
  rose: ['#fff1f2', '#ffe4e6', '#fecdd3', '#fda4af', '#fb7185', '#f43f5e', '#e11d48', '#be123c', '#9f1239', '#881337', '#4c0519'],
  amber: ['#fffbeb', '#fef3c7', '#fde68a', '#fcd34d', '#fbbf24', '#f59e0b', '#d97706', '#b45309', '#92400e', '#78350f', '#451a03'],
  emerald: ['#ecfdf5', '#d1fae5', '#a7f3d0', '#6ee7b7', '#34d399', '#10b981', '#059669', '#047857', '#065f46', '#064e3b', '#022c22'],
  red: ['#fef2f2', '#fee2e2', '#fecaca', '#fca5a5', '#f87171', '#ef4444', '#dc2626', '#b91c1c', '#991b1b', '#7f1d1d', '#450a0a'],
  purple: ['#faf5ff', '#f3e8ff', '#e9d5ff', '#d8b4fe', '#c084fc', '#a855f7', '#9333ea', '#7e22ce', '#6b21a8', '#581c87', '#3b0764'],
  blue: ['#eff6ff', '#dbeafe', '#bfdbfe', '#93c5fd', '#60a5fa', '#3b82f6', '#2563eb', '#1d4ed8', '#1e40af', '#1e3a8a', '#172554'],
  orange: ['#fff7ed', '#ffedd5', '#fed7aa', '#fdba74', '#fb923c', '#f97316', '#ea580c', '#c2410c', '#9a3412', '#7c2d12', '#431407'],
};
// The app's accent ("cyan" in the code) becomes the brand's restrained blue in both themes.
P.cyan = P.blue;

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(' ');

// Neutral surfaces/text, light theme: page #eef1f5, cards white, inputs near-white, borders light grey, text dark navy.
const LIGHT_SLATE = { 50: '#0b1220', 100: '#0f172a', 200: '#1e293b', 300: '#334155', 400: '#475569', 500: '#5b6779', 600: '#7b8798', 700: '#cbd5e1', 800: '#e2e8f0', 900: '#ffffff', 950: '#f6f8fb' };
// Solid shades (500-700: fills, buttons, dots) stay as they are; pale backgrounds (800-950) and light text (300-400) take the mirror shade.
const LIGHT_STEP = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 600, 700: 700, 800: 200, 900: 100, 950: 50 };
const mirror = (name, step) => P[name][STEPS.indexOf(LIGHT_STEP[step])];

let dark = '';
let light = '';
for (const name of Object.keys(P)) {
  STEPS.forEach((step, i) => {
    dark += `  --${name}-${step}: ${rgb(P[name][i])};\n`;
    light += `  --${name}-${step}: ${rgb(name === 'slate' ? LIGHT_SLATE[step] : mirror(name, step))};\n`;
  });
}

const css = `@tailwind base;
@tailwind components;
@tailwind utilities;

/*
 * Theme tokens. Every Tailwind colour the dashboard uses (slate, cyan, emerald, amber, rose, ...) is a CSS variable, so each component
 * follows the theme without per-component colour logic. Dark keeps Tailwind's own values; light maps each shade to its light-theme
 * counterpart (generated by scripts/gen-theme.mjs: node scripts/gen-theme.mjs src/app/globals.css). Semantic tokens below are for the shell and shared components.
 * The brand bar keeps the logo's own navy in both themes, so the supplied logo is never recoloured.
 */
/* .theme-dark: an area that always uses the dark values (the navy brand bar), whatever the page theme. */
:root,
:root.dark,
.theme-dark {
  color-scheme: dark;
${dark}  --white: 255 255 255;
  --black: 0 0 0;
  --background: 7 11 20;
  --surface: 15 23 42;
  --surface-muted: 11 17 32;
  --border-default: 30 41 59;
  --text-primary: 241 245 249;
  --text-secondary: 148 163 184;
  --primary: 37 99 235;
  --primary-hover: 59 130 246;
  --primary-foreground: 255 255 255;
  --focus: 96 165 250;
  --brand-bar: 9 14 27;
  --brand-red: 227 30 36;
  --brand-fg: 255 255 255;
}

:root.light {
  color-scheme: light;
${light}  --white: 11 18 32;
  --black: 0 0 0;
  --background: 238 241 245;
  --surface: 255 255 255;
  --surface-muted: 246 248 251;
  --border-default: 226 232 240;
  --text-primary: 15 23 42;
  --text-secondary: 71 85 105;
  --primary: 29 78 216;
  --primary-hover: 30 64 175;
  --primary-foreground: 255 255 255;
  --focus: 37 99 235;
  --brand-bar: 9 14 27;
  --brand-red: 227 30 36;
  --brand-fg: 255 255 255;
}

body {
  background-color: rgb(var(--background));
  color: rgb(var(--text-primary));
  font-family: Inter, "Segoe UI", -apple-system, BlinkMacSystemFont, Roboto, Helvetica, Arial, sans-serif;
  font-feature-settings: 'cv11', 'ss01';
}

:focus-visible {
  outline: 2px solid rgb(var(--focus));
  outline-offset: 2px;
}

/* Grid items may shrink below their content's width, so a long value wraps instead of widening the page on a phone. */
.grid > * {
  min-width: 0;
}

::selection {
  background: rgb(var(--primary) / 0.25);
}
`;

fs.writeFileSync(process.argv[2], css);
console.log('wrote', process.argv[2]);
